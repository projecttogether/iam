// Rejects private artifacts, unexpected hosts and email domains, internal
// names and common credential formats in the files of the repository (tracked
// ones and new ones that are not ignored), before a revision is shared. The
// hosts below are intentional. This check cannot tell whether prose or
// synthetic-looking values contain confidential information; review those too.
//
//   node scripts/check-public-repository.mjs
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync } from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");

const PUBLIC_HOSTS = new Set([
  "github.com",
  // The license's text.
  "www.apache.org",
  // SVG's namespace (public/favicon.svg).
  "www.w3.org",
  // The source of the app icon (apps/web/public/favicon.svg).
  "lucide.dev",
  // The tools of the image and the stack, and their documentation.
  "nodejs.org",
  "www.postgresql.org",
  "apt.postgresql.org",
  "docs.docker.com",
  "orm.drizzle.team",
  "hono.dev",
  "registry.npmjs.org",
  // Sign-in and its standards.
  "www.keycloak.org",
  "openid.net",
  "datatracker.ietf.org",
  "www.rfc-editor.org",
  // What the connections and the docs connect to.
  "admin.googleapis.com",
  "oauth2.googleapis.com",
  "www.googleapis.com",
  "developers.google.com",
  "api.hubapi.com",
  "app.hubspot.com",
  "developers.hubspot.com",
  "api.notion.com",
  "www.notion.so",
  "api.personio.de",
  "developer.personio.de",
  "slack.com",
  "docs.slack.dev",
]);
/** Public hosts by their domain, as examples in the docs. */
const PUBLIC_HOST_SUFFIXES = [".slack.com"];
const LOCAL_ADDRESSES = new Set(["127.0.0.1", "0.0.0.0"]);
/** Invented addresses in tests, by file (and this file, which lists them). */
const REVIEWED_ADDRESSES = new Map([
  // An address literal that the email check refuses.
  ["apps/server/src/adapters/personio.test.ts", new Set(["01.1.1.1"])],
  ["scripts/check-public-repository.mjs", new Set(["01.1.1.1"])],
]);
/** Google's domain of service accounts, in invented keys of the tests. */
const PUBLIC_EMAIL_SUFFIXES = [".iam.gserviceaccount.com"];

/** Binary files someone has looked at: ProjectTogether's logo and the screenshots of the docs. */
const REVIEWED_BINARIES = new Set([
  "apps/web/src/assets/projecttogether-logo.png",
  "docs/screenshots/keycloak-connection.png",
  "docs/screenshots/onboarding.png",
  "docs/screenshots/person.png",
]);
/** Generated by npm: the registry and funding links of the dependencies. */
const GENERATED = new Set(["package-lock.json"]);

const PRIVATE_SUFFIXES = new Set([
  ".db",
  ".sqlite3",
  ".dump",
  ".eml",
  ".pem",
  ".key",
  ".p12",
  ".pfx",
  ".log",
  ".tar",
  ".zip",
]);
const TOKEN = new RegExp(
  [
    // A private key with a body (the tests' keys are cut short).
    String.raw`-----BEGIN [A-Z ]*PRIVATE KEY-----[\s\S]{64,}?-----END`,
    String.raw`\bgh[pousr]_[A-Za-z0-9]{30,}`,
    String.raw`\bgithub_pat_[A-Za-z0-9_]{30,}`,
    String.raw`\bAKIA[A-Z0-9]{16}\b`,
    String.raw`\bxox[baprs]-[A-Za-z0-9-]{20,}`,
    String.raw`\bsntry[su]_[A-Za-z0-9+/=_-]{20,}`,
    String.raw`\bnpm_[A-Za-z0-9]{36}\b`,
  ].join("|"),
);
/** ProjectTogether's servers and internal domains belong in its infrastructure repository. */
const INTERNAL = /\bprojecttogether\.net\b|\bpt-(?:prd|stg|tst|dev|backup)-[a-z0-9-]+/i;
const URL_PATTERN = /\b(?:https?|postgres|postgresql):\/\/[^\s"'<>`)\]\\]+/g;
const EMAIL = /\b[\w.+-]+@([\w-]+(?:\.[\w-]+)*\.[A-Za-z]{2,})\b/g;
const IPV4 = /(?<![\w.])(?:\d{1,3}\.){3}\d{1,3}(?![\w.])/g;

const isExample = (host) =>
  /(^|\.)example\.(org|com|net)$/.test(host) || /\.(test|invalid|example|localhost)$/.test(host);

function hostAllowed(host) {
  return (
    PUBLIC_HOSTS.has(host) ||
    PUBLIC_HOST_SUFFIXES.some((suffix) => host.endsWith(suffix)) ||
    LOCAL_ADDRESSES.has(host) ||
    isExample(host) ||
    // Without a dot: localhost, services on a Compose network, test values.
    (!host.includes(".") && !host.includes(":"))
  );
}

function hostOf(text) {
  try {
    // Several hosts (postgresql://db1,db2/…) and templates are not one host.
    return new URL(text.replace(/^postgres(ql)?:/, "http:")).hostname.toLowerCase();
  } catch {
    return null;
  }
}

function check(name) {
  const file = path.join(ROOT, name);
  const base = path.basename(name);
  if (
    PRIVATE_SUFFIXES.has(path.extname(name).toLowerCase()) ||
    (base.startsWith(".env") && !base.endsWith(".example"))
  ) {
    return [`${name}: private artifact type`];
  }
  const bytes = readFileSync(file);
  let content;
  try {
    content = new TextDecoder("utf-8", { fatal: true }).decode(bytes);
  } catch {
    return REVIEWED_BINARIES.has(name) ? [] : [`${name}: binary asset requires review`];
  }
  if (bytes.includes(0) && !REVIEWED_BINARIES.has(name)) return [`${name}: binary asset requires review`];
  const errors = [];
  if (TOKEN.test(content)) errors.push(`${name}: credential-shaped value`);
  if (INTERNAL.test(content)) errors.push(`${name}: internal server or domain name`);
  for (const [address] of content.matchAll(IPV4)) {
    const reviewed = REVIEWED_ADDRESSES.get(name)?.has(address);
    if (
      !LOCAL_ADDRESSES.has(address) &&
      !reviewed &&
      address.split(".").every((part) => Number(part) <= 255)
    ) {
      errors.push(`${name}: IP address ${address}`);
    }
  }
  if (GENERATED.has(name)) return errors;
  for (const match of content.matchAll(EMAIL)) {
    const domain = match[1].toLowerCase();
    if (!isExample(domain) && !PUBLIC_EMAIL_SUFFIXES.some((suffix) => domain.endsWith(suffix))) {
      errors.push(`${name}: non-example email domain ${domain}`);
    }
  }
  for (const [match] of content.matchAll(URL_PATTERN)) {
    // Not the punctuation after an address at the end of a sentence.
    const host = hostOf(match.replace(/[.,;:]+$/, ""));
    if (host && !hostAllowed(host)) errors.push(`${name}: unexpected URL host ${host}`);
  }
  return errors;
}

const names = execFileSync("git", ["ls-files", "-z", "--cached", "--others", "--exclude-standard"], {
  cwd: ROOT,
  encoding: "utf8",
})
  .split("\0")
  .filter((name) => name && existsSync(path.join(ROOT, name)));
const unique = [...new Set(names)];
const errors = [...new Set(unique.flatMap(check))].sort();
/* eslint-disable no-console -- a command's output */
if (errors.length > 0) {
  console.error(errors.join("\n"));
  process.exit(1);
}
console.log(`Public repository checks passed for ${unique.length} files.`);
